"""ChangeRequest service enforcing plain-language consent, expiry, and duplicate detection.

Caretaker edits generate a ChangeRequest that only the elder can approve or reject.
"""

from datetime import datetime, timedelta, timezone
import uuid
from typing import Any, Dict, List, Optional, Tuple
from fastapi import HTTPException, status
from app.core.database import db
from app.models.audit import AuditEntry
from app.models.change_request import ChangeRequest, ChangeRequestStatus, EntityType
from app.models.medication import Medication
from app.models.appointment import Appointment


def log_audit(
    elder_id: str,
    action: str,
    actor_id: str,
    actor_role: str,
    details: Optional[Dict[str, Any]] = None,
    ip_address: Optional[str] = None,
) -> AuditEntry:
    """Helper to record an immutable audit entry."""
    audit_id = f"audit_{uuid.uuid4().hex[:8]}"
    now_iso = datetime.now(timezone.utc).isoformat()
    entry = AuditEntry(
        id=audit_id,
        elder_id=elder_id,
        action=action,
        actor_id=actor_id,
        actor_role=actor_role,
        details=details or {},
        ip_address=ip_address,
        timestamp=now_iso,
    )
    db.set("audit_logs", audit_id, entry.model_dump())
    return entry


def generate_plain_language_summary(
    entity_type: EntityType,
    proposed_changes: Dict[str, Any],
    reason: str,
    created_by: str,
) -> str:
    """Generate a clear, respectful plain-language explanation for elderly review."""
    if entity_type == EntityType.MEDICATION:
        med_name = proposed_changes.get("name", "medication")
        dosage = proposed_changes.get("dosage")
        schedule = proposed_changes.get("schedule_times")
        schedule_text = f" at {', '.join(schedule)}" if schedule else ""

        if "id" in proposed_changes and db.get("medications", proposed_changes["id"]):
            parts = []
            if dosage:
                parts.append(f"change dose to {dosage}")
            if schedule:
                parts.append(f"adjust time to {', '.join(schedule)}")
            instructions = proposed_changes.get("instructions")
            if instructions:
                parts.append(f"instructions: '{instructions}'")
            action_desc = ", and ".join(parts) if parts else "update details"
            return (
                f"{created_by} suggests to {action_desc} for your {med_name}. "
                f"Reason: {reason}"
            )
        return (
            f"{created_by} suggests adding {med_name} ({dosage or ''}{schedule_text}) "
            f"to your routine. Reason: {reason}"
        )

    elif entity_type == EntityType.APPOINTMENT:
        title = proposed_changes.get("title", "doctor visit")
        doctor = proposed_changes.get("doctor_name", "doctor")
        loc = proposed_changes.get("location", "")
        time_val = proposed_changes.get("scheduled_time", "")
        return (
            f"{created_by} suggests scheduling '{title}' with {doctor} "
            f"at {loc} on {time_val}. Reason: {reason}"
        )

    return f"{created_by} suggested updates. Reason: {reason}"


def check_and_update_expiry(cr: ChangeRequest) -> ChangeRequest:
    """Check if ChangeRequest has exceeded its expiry time and mark EXPIRED if needed."""
    if cr.status == ChangeRequestStatus.PENDING:
        try:
            exp_dt = datetime.fromisoformat(cr.expires_at)
            now_dt = datetime.now(timezone.utc)
            if now_dt > exp_dt:
                updated = db.update("change_requests", cr.id, {
                    "status": ChangeRequestStatus.EXPIRED.value,
                })
                log_audit(
                    elder_id=cr.elder_id,
                    action="CHANGE_REQUEST_EXPIRED",
                    actor_id="system",
                    actor_role="system",
                    details={"change_request_id": cr.id},
                )
                return ChangeRequest(**updated)
        except Exception:
            pass
    return cr


def create_change_request(
    elder_id: str,
    entity_type: EntityType,
    proposed_changes: Dict[str, Any],
    reason: str,
    created_by: str,
    entity_id: Optional[str] = None,
    plain_language_summary: Optional[str] = None,
    ai_generated: bool = False,
    expires_in_hours: int = 72,
) -> ChangeRequest:
    """Create a new change request with duplicate prevention and expiry tracking.

    Args:
        elder_id: The target elder.
        entity_type: MEDICATION or APPOINTMENT.
        proposed_changes: Field overrides.
        reason: Justification for changes.
        created_by: Author name/ID.
        entity_id: Target entity identifier.
        plain_language_summary: Optional explicit summary.
        ai_generated: Whether generated by AI assistant.
        expires_in_hours: Hours until expiration (default 72).

    Returns:
        Persisted ChangeRequest with PENDING status.

    Raises:
        HTTPException 409: If a duplicate pending request already exists for this entity.
    """
    target_id = entity_id or proposed_changes.get("id")

    # Duplicate Request Prevention: Check for existing pending request on same entity
    if target_id:
        existing_pendings = db.list(
            "change_requests",
            filters=[
                ("elder_id", "==", elder_id),
                ("entity_type", "==", entity_type.value),
                ("status", "==", ChangeRequestStatus.PENDING.value),
            ],
        )
        for ep in existing_pendings:
            ep_model = check_and_update_expiry(ChangeRequest(**ep))
            if ep_model.status == ChangeRequestStatus.PENDING and ep_model.entity_id == target_id:
                raise HTTPException(
                    status_code=status.HTTP_409_CONFLICT,
                    detail=(
                        f"A pending change request for this {entity_type.value.lower()} "
                        f"already exists (ID: {ep_model.id}). Please review or resolve it first."
                    ),
                )

    cr_id = f"cr_{uuid.uuid4().hex[:8]}"
    now = datetime.now(timezone.utc)
    expires_at = (now + timedelta(hours=expires_in_hours)).isoformat()
    now_iso = now.isoformat()

    summary = plain_language_summary or generate_plain_language_summary(
        entity_type=entity_type,
        proposed_changes=proposed_changes,
        reason=reason,
        created_by=created_by,
    )

    cr = ChangeRequest(
        id=cr_id,
        elder_id=elder_id,
        entity_type=entity_type,
        entity_id=target_id,
        proposed_changes=proposed_changes,
        reason=reason,
        plain_language_summary=summary,
        ai_generated=ai_generated,
        created_by=created_by,
        status=ChangeRequestStatus.PENDING,
        created_at=now_iso,
        expires_at=expires_at,
    )

    saved = db.set("change_requests", cr_id, cr.model_dump())
    log_audit(
        elder_id=elder_id,
        action="CHANGE_REQUEST_CREATED",
        actor_id=created_by,
        actor_role="caretaker" if not ai_generated else "ai_assistant",
        details={
            "change_request_id": cr_id,
            "entity_type": entity_type.value,
            "entity_id": target_id,
            "expires_at": expires_at,
        },
    )
    return ChangeRequest(**saved)


def list_change_requests(
    elder_id: str,
    status_filter: Optional[ChangeRequestStatus] = None,
) -> List[ChangeRequest]:
    """Retrieve change requests for an elder, updating expired records."""
    filters = [("elder_id", "==", elder_id)]
    if status_filter:
        filters.append(("status", "==", status_filter.value))

    records = db.list("change_requests", filters=filters, order_by="created_at", descending=True)
    models = [check_and_update_expiry(ChangeRequest(**r)) for r in records]
    if status_filter:
        models = [m for m in models if m.status == status_filter]
    return models


def approve_change_request(
    change_request_id: str,
    reviewer_id: str,
    reviewer_role: str,
) -> Tuple[ChangeRequest, Any]:
    """Approve a ChangeRequest and apply mutations to the underlying entity.

    Permission Rule: Only the 'elder' role can approve change requests.
    Validates that request has not expired or already been decided.

    Args:
        change_request_id: ID of the pending change request.
        reviewer_id: User ID approving the request.
        reviewer_role: Role of the approving user. Must be 'elder'.

    Returns:
        Tuple of (updated ChangeRequest, updated or created entity).

    Raises:
        HTTPException 403: If reviewer is not the elder.
        HTTPException 404: If change request is not found.
        HTTPException 400: If change request has expired or is not PENDING.
    """
    if reviewer_role != "elder":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Permission denied: Only the elder has authority to approve change requests.",
        )

    cr_dict = db.get("change_requests", change_request_id)
    if not cr_dict:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"ChangeRequest '{change_request_id}' not found.",
        )

    cr = check_and_update_expiry(ChangeRequest(**cr_dict))
    if cr.status == ChangeRequestStatus.EXPIRED:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="This change request has expired and can no longer be approved.",
        )

    if cr.status != ChangeRequestStatus.PENDING:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"ChangeRequest '{change_request_id}' is already {cr.status.value}.",
        )

    now_iso = datetime.now(timezone.utc).isoformat()
    changes = cr.proposed_changes
    target_entity = None

    if cr.entity_type == EntityType.MEDICATION:
        med_id = cr.entity_id or changes.get("id")
        if med_id and db.get("medications", med_id):
            clean_updates = {k: v for k, v in changes.items() if k != "id"}
            clean_updates["updated_at"] = now_iso
            updated_dict = db.update("medications", med_id, clean_updates)
            target_entity = Medication(**updated_dict)
        else:
            new_id = med_id or f"med_{uuid.uuid4().hex[:8]}"
            med_data = dict(changes)
            med_data.update({
                "id": new_id,
                "elder_id": cr.elder_id,
                "is_active": True,
                "created_at": now_iso,
                "updated_at": now_iso,
            })
            saved_dict = db.set("medications", new_id, med_data)
            target_entity = Medication(**saved_dict)

    elif cr.entity_type == EntityType.APPOINTMENT:
        appt_id = cr.entity_id or changes.get("id")
        if appt_id and db.get("appointments", appt_id):
            clean_updates = {k: v for k, v in changes.items() if k != "id"}
            updated_dict = db.update("appointments", appt_id, clean_updates)
            target_entity = Appointment(**updated_dict)
        else:
            new_id = appt_id or f"appt_{uuid.uuid4().hex[:8]}"
            appt_data = dict(changes)
            appt_data.update({
                "id": new_id,
                "elder_id": cr.elder_id,
                "created_at": now_iso,
            })
            saved_dict = db.set("appointments", new_id, appt_data)
            target_entity = Appointment(**saved_dict)

    # Mark change request as approved
    updated_cr_dict = db.update("change_requests", change_request_id, {
        "status": ChangeRequestStatus.APPROVED.value,
        "reviewed_by": reviewer_id,
        "reviewed_at": now_iso,
    })

    log_audit(
        elder_id=cr.elder_id,
        action="CHANGE_REQUEST_APPROVED",
        actor_id=reviewer_id,
        actor_role=reviewer_role,
        details={"change_request_id": change_request_id, "entity_type": cr.entity_type.value},
    )

    return ChangeRequest(**updated_cr_dict), target_entity


def reject_change_request(
    change_request_id: str,
    reviewer_id: str,
    reviewer_role: str,
    reason: Optional[str] = None,
) -> ChangeRequest:
    """Reject a ChangeRequest without mutating the entity.

    Permission Rule: Only the 'elder' role can reject change requests.

    Args:
        change_request_id: ID of the pending change request.
        reviewer_id: User ID rejecting the request.
        reviewer_role: Role of the rejecting user. Must be 'elder'.
        reason: Optional rejection reason.

    Returns:
        Updated ChangeRequest with REJECTED status.

    Raises:
        HTTPException 403: If reviewer is not the elder.
        HTTPException 404: If change request is not found.
        HTTPException 400: If change request has expired or is not in PENDING status.
    """
    if reviewer_role != "elder":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Permission denied: Only the elder has authority to reject change requests.",
        )

    cr_dict = db.get("change_requests", change_request_id)
    if not cr_dict:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"ChangeRequest '{change_request_id}' not found.",
        )

    cr = check_and_update_expiry(ChangeRequest(**cr_dict))
    if cr.status == ChangeRequestStatus.EXPIRED:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="This change request has expired and can no longer be modified.",
        )

    if cr.status != ChangeRequestStatus.PENDING:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"ChangeRequest '{change_request_id}' is already {cr.status.value}.",
        )

    now_iso = datetime.now(timezone.utc).isoformat()
    updated_cr_dict = db.update("change_requests", change_request_id, {
        "status": ChangeRequestStatus.REJECTED.value,
        "reviewed_by": reviewer_id,
        "reviewed_at": now_iso,
    })

    log_audit(
        elder_id=cr.elder_id,
        action="CHANGE_REQUEST_REJECTED",
        actor_id=reviewer_id,
        actor_role=reviewer_role,
        details={"change_request_id": change_request_id, "reason": reason},
    )

    return ChangeRequest(**updated_cr_dict)
